namespace TurboVector.Tests;

public class RotationParityTests
{
    [Fact]
    public void RotationMatchesPinnedRustF32Goldens()
    {
        AssertRotationBits(
            Enumerable.Range(0, 8).Select(i => i - 3.5f).ToArray(),
            [
                1071644673, 3224371200, 1048575995, 1061158910,
                1074790400, 1083703296, 3214934014, 1067450369,
            ]);

        AssertRotationBits(
            Enumerable.Range(0, 24).Select(i => ((i * 7) % 11) - 5.0f).ToArray(),
            [
                1081081856, 1088421887, 3204448256, 1076887552, 3221225472,
                3224371200, 1061158914, 1084227583, 1052770317, 1063256064,
                1072693248, 1052770303, 3237216256, 3225944064, 1063256063,
                3206545409, 3229089792, 3221749760, 1085014015, 1040187401,
                3225944064, 3222798336, 1040187401, 1072693248,
            ]);

        AssertRotationBits(
            Enumerable.Range(0, 64).Select(i => ((i * 13) % 29) - 14.0f).ToArray(),
            [
                1077149696, 3246260224, 1063256064, 1096482816, 1076625408,
                3232497664, 1081081856, 3244621824, 1089994752, 1093337088,
                1096220672, 3229876224, 3204448256, 1075052544, 1092812800,
                3246391296, 1086062592, 1086193664, 1095172096, 1095761920,
                3225419776, 3238592512, 3207593984, 3230138368, 1071120384,
                1088159744, 3200253952, 3240820736, 3209691136, 3223322624,
                1093533696, 1091764224, 3232759808, 1078722560, 3233677312,
                3225419776, 1068498944, 3179282432, 1074528256, 3235905536,
                3243048960, 3252027392, 3233021952, 1091239936, 3221487616,
                3236691968, 1087111168, 3224109056, 1088552960, 1094189056,
                3210739712, 1088028672, 1085669376, 3222274048, 3240361984,
                3225157632, 3242328064, 1096482816, 3226206208, 1063256064,
                3234070528, 3243704320, 3234201600, 1083703296,
            ]);
    }

    private static void AssertRotationBits(float[] input, uint[] expected)
    {
        Rotation rotation = Rotation.Create(input.Length);
        float[] scratch = new float[input.Length];
        rotation.Apply(input, scratch);

        Assert.Equal(expected, input.Select(BitConverter.SingleToUInt32Bits));
    }
}
